#!/usr/bin/env python3
"""Generates src/assets.c, src/assets.h, src/music_data.inc from the art/world/music modules."""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from art import *
import world
import music

ROOT = os.path.join(os.path.dirname(__file__), '..')
SRC = os.path.join(ROOT, 'src')


def carr(ctype, name, data, per=16, const=True):
    lines = []
    for i in range(0, len(data), per):
        lines.append('    ' + ','.join(str(v) for v in data[i:i + per]))
    return '%s%s %s[%d] = {\n%s\n};\n' % ('const ' if const else '', ctype, name, len(data), ',\n'.join(lines))


def main():
    ts = build_tileset()
    ss = build_sprites()
    th = themes()

    # ---------------------------------------------------------- rooms
    rooms_out = []
    metas = []
    for ri, r in enumerate(world.ROOMS):
        g = r.g

        def solid(x, y):
            if x < 0 or x >= world.W or y < 0 or y >= world.H:
                return True
            return g[y][x] == '#'
        tiles = []
        ents = []
        npc_i = tab_i = 0
        for y in range(world.H):
            for x in range(world.W):
                ch = g[y][x]
                name = None
                if ch == '#':
                    mask = (0 if solid(x, y - 1) else U) | (0 if solid(x, y + 1) else D) | \
                           (0 if solid(x - 1, y) else L) | (0 if solid(x + 1, y) else R)
                    if mask & U:
                        name = 'moss%d' % mask
                    elif mask == 0:
                        h = (x * 7 + y * 13) % 5
                        name = 'rockin%d' % h if h in (1, 2) else 'rock0'
                    else:
                        name = 'rock%d' % mask
                elif ch == '.':
                    h = (x * 31 + y * 17 + ri * 5) % 23
                    name = 'empty1' if h < 3 else ('empty2' if h == 7 else 'empty')
                elif ch == '-':
                    name = 'oneway'
                elif ch == '^':
                    name = 'spike'
                elif ch == 'v':
                    name = 'stal'
                elif ch == 'n':
                    name = 'stag'
                elif ch == 'w':
                    name = 'vine' if (x + y) % 2 else 'vine2'
                elif ch == 'i':
                    name = 'chain'
                elif ch == 'l':
                    name = 'lamp'
                elif ch == 'c':
                    name = 'crystal'
                elif ch == 'm':
                    name = 'mush'
                elif ch == 'p':
                    name = 'pillar'
                elif ch == 'P':
                    name = 'pillarT'
                elif ch == 'b':
                    name = 'backbrick'
                elif ch == 'B':
                    name = 'benchL'
                    ents.append((world.ENT['BENCH'], x, y, 0))
                elif ch == 't':
                    name = 'tablet'
                    ents.append((world.ENT['TABLET'], x, y, world.TEXT_ORDER.index(r.tablet_args[tab_i])))
                    tab_i += 1
                elif ch in 'SkfNCHW':
                    name = 'empty'
                    kind = dict(S='START', k='CRAWLID', f='FLY', N='NPC', C='CLOAK', H='HEART', W='BOSS')[ch]
                    arg = 0
                    if ch == 'N':
                        arg = r.npc_args[npc_i]
                        npc_i += 1
                    ents.append((world.ENT[kind], x, y, arg))
                else:
                    raise SystemExit('unknown char %r in room %d' % (ch, ri))
                tiles.append(ts[name])
        # right half of benches
        for (t, x, y, a) in ents:
            if t == world.ENT['BENCH']:
                tiles[y * world.W + x + 1] = ts['benchR']
        assert len(ents) <= 8, (ri, len(ents))
        rooms_out.append(tiles)
        metas.append((r, ents))

    # ---------------------------------------------------------- texts
    pages = []
    tindex = []
    for name in world.TEXT_ORDER:
        wp = world.wrap_pages(world.TEXTS[name])
        tindex.append((len(pages), len(wp)))
        for p in wp:
            flat = ''.join(p)
            for c in flat:
                assert c in GLYPHS, (name, c)
            pages.append([ord(c) for c in flat])

    # ---------------------------------------------------------- title
    tcv = title_image()
    ttiles, tmap = tiles_from_canvas(tcv)
    assert len(ttiles) <= 256
    tattr = []
    for ty in range(18):
        for tx in range(20):
            tattr.append(TITLE_ROW_PAL[ty] | 0x08)
    tpal = [c555(c) for p in title_palettes() for c in p]

    # ---------------------------------------------------------- header
    h = []
    h.append('/* generated by assets/build_assets.py - do not edit */\n#ifndef ASSETS_H\n#define ASSETS_H\n')
    h.append('#include <gb/gb.h>\n#include <stdint.h>\n')
    h.append('#define NO_EXIT 0xFF\n#define NUM_ROOMS %d\n' % len(world.ROOMS))
    for k, v in world.ENT.items():
        h.append('#define ENT_%s %d\n' % (k, v))
    h.append('typedef struct { uint8_t type, tx, ty, arg; } Ent;\n')
    h.append('typedef struct { uint8_t exit_l, exit_r, exit_u, exit_d, theme, nent; char name[16]; Ent ent[8]; } RoomMeta;\n')
    h.append('#define NBG_TILES %d\n#define NSPR_TILES %d\n' % (len(ts.tiles), len(ss.data)))
    for n in ['empty', 'hudbg', 'mask_full', 'mask_empty', 'arrow_up', 'font', 'b_tl', 'b_t', 'b_tr', 'b_l', 'b_r',
              'b_bl', 'b_b', 'b_br', 'b_fill', 'rockin1', 'rock0']:
        h.append('#define TL_%s %d\n' % (n.upper(), ts[n]))
    for part in range(3):
        h.append('#define TL_SOUL%d %d\n' % (part, ts['soul%d_0' % part]))
    for n, b in ss.names.items():
        h.append('#define SPR_%s %d\n' % (n, b))
    for i, n in enumerate(world.TEXT_ORDER):
        h.append('#define TXT_%s %d\n' % (n, i))
    for i, n in enumerate(music.SONG_ORDER):
        h.append('#define SONG_%s %d\n' % (n, i))
    h.append('#define NUM_SONGS %d\n' % len(music.SONG_ORDER))
    h.append('''
void gfx_load_ingame(uint8_t *flags, uint8_t *attrs) BANKED;
void gfx_load_title(uint16_t *pal32) BANKED;
void gfx_theme_pals(uint8_t theme, uint16_t *bg32) BANKED;
void gfx_obj_pals(uint16_t *obj32) BANKED;
void room_load(uint8_t id, uint8_t *map, RoomMeta *m) BANKED;
uint8_t text_npages(uint8_t id) BANKED;
void text_page(uint8_t id, uint8_t page, uint8_t *dst72) BANKED;
#endif
''')
    open(os.path.join(SRC, 'assets.h'), 'w').write(''.join(h))

    # ---------------------------------------------------------- C (split in 3 banked units)
    def head(extra=''):
        return ('/* generated by assets/build_assets.py - do not edit */\n#pragma bank 255\n'
                '#include <gb/gb.h>\n#include <gb/cgb.h>\n#include <string.h>\n#include "assets.h"\n\n' + extra)
    gfx = [head()]
    bgdata = []
    for t in ts.tiles:
        bgdata += tile_bytes(t)
    gfx.append(carr('uint8_t', 'bg_tiles', bgdata))
    gfx.append(carr('uint8_t', 'spr_tiles', [b for t in ss.data for b in t]))
    flags = ts.flags + [0] * (256 - len(ts.flags))
    attrs = [ts.pal[i] | 0x08 for i in range(len(ts.tiles))] + [0] * (256 - len(ts.tiles))
    gfx.append(carr('uint8_t', 'tile_flags', flags))
    gfx.append(carr('uint8_t', 'tile_attrs', attrs))
    tp = []
    for t in range(4):
        for p in th[t]:
            tp += [c555(x) for x in p]
    gfx.append(carr('uint16_t', 'theme_pals', tp, 8))
    op = []
    for p in OBJ_PALS:
        op += [c555(x) for x in p]
    gfx.append(carr('uint16_t', 'obj_pals', op, 8))
    gfx.append('''
void gfx_load_ingame(uint8_t *flags, uint8_t *attrs) BANKED {
    VBK_REG = 1;
    set_bkg_data(0, NBG_TILES, bg_tiles);
    VBK_REG = 0;
    set_sprite_data(0, NSPR_TILES, spr_tiles);
    memcpy(flags, tile_flags, 256);
    memcpy(attrs, tile_attrs, 256);
}
void gfx_theme_pals(uint8_t theme, uint16_t *bg32) BANKED {
    memcpy(bg32, theme_pals + theme * 32, 64);
}
void gfx_obj_pals(uint16_t *obj32) BANKED {
    memcpy(obj32, obj_pals, 64);
}
''')
    open(os.path.join(SRC, 'assets_gfx.c'), 'w').write(''.join(gfx))

    tt = [head()]
    tdata = []
    for t in ttiles:
        tdata += t
    tt.append(carr('uint8_t', 'title_tiles', tdata))
    tt.append(carr('uint8_t', 'title_map', tmap, 20))
    tt.append(carr('uint8_t', 'title_attr', tattr, 20))
    tt.append(carr('uint16_t', 'title_pal', tpal, 8))
    tt.append('''
void gfx_load_title(uint16_t *pal32) BANKED {
    VBK_REG = 1;
    set_bkg_data(0, %d, title_tiles);
    VBK_REG = 0;
    set_bkg_tiles(0, 0, 20, 18, title_map);
    VBK_REG = 1;
    set_bkg_tiles(0, 0, 20, 18, title_attr);
    VBK_REG = 0;
    memcpy(pal32, title_pal, 64);
}
''' % len(ttiles))
    open(os.path.join(SRC, 'assets_title.c'), 'w').write(''.join(tt))

    wd = [head()]
    wd.append('const uint8_t room_maps[NUM_ROOMS][320] = {\n')
    for t in rooms_out:
        wd.append('{' + ','.join(str(v) for v in t) + '},\n')
    wd.append('};\n')
    wd.append('const RoomMeta room_meta[NUM_ROOMS] = {\n')
    for (r, ents) in metas:
        e = ','.join('{%d,%d,%d,%d}' % x for x in ents)
        if not e:
            e = '{0,0,0,0}'
        wd.append('{%d,%d,%d,%d,%d,%d,"%s",{%s}},\n' % (
            r.exits['l'], r.exits['r'], r.exits['u'], r.exits['d'], r.theme, len(ents), r.name, e))
    wd.append('};\n')
    wd.append(carr('uint8_t', 'text_data', [b for p in pages for b in p], 72))
    wd.append(carr('uint8_t', 'text_first', [a for a, b in tindex]))
    wd.append(carr('uint8_t', 'text_count', [b for a, b in tindex]))
    wd.append('''
void room_load(uint8_t id, uint8_t *map, RoomMeta *m) BANKED {
    memcpy(map, room_maps[id], 320);
    memcpy(m, &room_meta[id], sizeof(RoomMeta));
}
uint8_t text_npages(uint8_t id) BANKED { return text_count[id]; }
void text_page(uint8_t id, uint8_t page, uint8_t *dst) BANKED {
    memcpy(dst, text_data + (uint16_t)(text_first[id] + page) * 72, 72);
}
''')
    open(os.path.join(SRC, 'assets_world.c'), 'w').write(''.join(wd))

    # ---------------------------------------------------------- music
    sq, wv = music.freq_tables()
    m = ['/* generated by assets/build_assets.py - do not edit */\n']
    m.append(carr('uint16_t', 'freq_sq', sq, 12))
    m.append(carr('uint16_t', 'freq_wv', wv, 12))
    names = []
    for i, n in enumerate(music.SONG_ORDER):
        s = music.SONGS[n]
        d1 = [x for p in s['ch1'] for x in p]
        d3 = [x for p in s['ch3'] for x in p]
        m.append(carr('uint8_t', 'song%d_ch1' % i, d1 + [255, 0], 16))
        m.append(carr('uint8_t', 'song%d_ch3' % i, d3 + [255, 0], 16))
    m.append('const SongDef songs[%d] = {\n' % len(music.SONG_ORDER))
    for i, n in enumerate(music.SONG_ORDER):
        s = music.SONGS[n]
        m.append('  {song%d_ch1, song%d_ch3, %d, %d},\n' % (i, i, s['tick'], s['duty']))
    m.append('};\n')
    open(os.path.join(SRC, 'music_data.inc'), 'w').write(''.join(m))

    print('bg tiles %d/256, spr tiles %d/256, title tiles %d/256, rooms %d, text pages %d' % (
        len(ts.tiles), len(ss.data), len(ttiles), len(world.ROOMS), len(pages)))


if __name__ == '__main__':
    main()
